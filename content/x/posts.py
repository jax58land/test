def x_length(body):
    """X の文字数の目安。【URL:…】は実際のURL（全角換算で約12字）として数える。"""
    import re
    return len(re.sub(r"【URL:[^】]+】", "＊" * 12, body))


def main():
    out = ["# X 投稿ネタ30本（オーナーが使うかは任意）", "",
           "- コピペで投稿できます。URLの場所は出品後に `tools/apply_urls.py` で差し替え（差し替え済みは content/ready/x/posts.md）。1日1本ペース、宣伝は5本に1本くらいが目安",
           "- 数値は商品・記事と同じ検証済みのものだけ。本文は140字以内（自動チェック済み）", ""]
    for i, (tag, body) in enumerate(POSTS, 1):
        n = x_length(body)
        assert n <= 140, f"{i}本目が{n}字"
        out += [f"## {i}. {tag}（{n}字）", "```", body, "```", ""]
    assert len(POSTS) == 30
    path = Path(__file__).with_name("posts.md")
    path.write_text("\n".join(out), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(main())
